#!/usr/bin/env python3
"""Export and verify a committed, offline Forge compiler/runtime/stdlib bundle."""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import stat
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
REPOSITORIES = {name: f"https://github.com/forge-language/{name}.git"
                for name in ("forge", "forge-runtime", "forge-stdlib")}
CMAKE = '''cmake_minimum_required(VERSION 3.16)
project(portfolio_forge_toolchain LANGUAGES C)
set(FORGE_RUNTIME_SOURCE_DIR "${CMAKE_CURRENT_SOURCE_DIR}/sources/forge-runtime" CACHE PATH "Pinned runtime" FORCE)
set(FORGE_STDLIB_SOURCE_DIR "${CMAKE_CURRENT_SOURCE_DIR}/sources/forge-stdlib" CACHE PATH "Pinned stdlib" FORCE)
option(FORGE_ENABLE_GPU "Enable OpenCL" OFF)
option(FORGE_ENABLE_IO_URING "Enable io_uring" OFF)
option(FORGE_ENABLE_TLS "Enable stdlib TLS" OFF)
add_subdirectory(sources/forge)
'''
README = '''# Pinned Forge toolchain

This directory is generated by `python3 scripts/update-forge-toolchain.py`.
Compiler, runtime and stdlib are exported from committed upstream revisions,
including their original build files, tests and licenses. No Git checkout or
network is required to build the bundled sources. Revisions and content hashes
are in `lock.json`. Do not edit generated sources directly.

Update: `python3 scripts/update-forge-toolchain.py --revision <compiler-ref>`.
Verify: `python3 scripts/update-forge-toolchain.py --check`.
See `../README.md` for local repositories, validation and rollback.
'''


def git(directory, *args):
    return subprocess.check_output(["git", "-C", str(directory), *args],
                                   env={**os.environ, "GIT_MASTER": "1"})


def tree_hash(directory):
    digest = hashlib.sha256()
    for path in sorted(directory.rglob("*")):
        if path.is_symlink():
            raise ValueError("Symlink in source bundle: " + str(path))
        if path.is_file():
            relative = path.relative_to(directory).as_posix()
            executable = bool(path.stat().st_mode & stat.S_IXUSR)
            digest.update(relative.encode() + b"\0" + bytes([executable]) + path.read_bytes() + b"\0")
    return digest.hexdigest()


def export(repository, revision, destination):
    resolved = git(repository, "rev-parse", "--verify", "--end-of-options",
                   revision + "^{commit}").decode().strip()
    if not re.fullmatch(r"[0-9a-f]{40}", resolved):
        raise ValueError("Expected a full Git commit")
    archive = git(repository, "archive", "--format=tar", resolved)
    destination.mkdir()
    with tarfile.open(fileobj=io.BytesIO(archive)) as source:
        for member in source.getmembers():
            path = PurePosixPath(member.name)
            if path.is_absolute() or ".." in path.parts or not (member.isfile() or member.isdir()):
                raise ValueError("Unsafe Git archive member: " + member.name)
            target = destination.joinpath(*path.parts)
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(source.extractfile(member).read())
                target.chmod(0o755 if member.mode & stat.S_IXUSR else 0o644)
    return resolved


def pin(source, name):
    match = re.search(r'set\(' + name + r'\s+"([0-9a-f]{40})"\s*\)', source.read_text())
    if not match:
        raise ValueError(f"Missing immutable {name} in {source}")
    return match.group(1)


def verify(bundle, lock):
    if lock.get("schema") != 1 or set(lock.get("components", {})) != set(REPOSITORIES):
        raise ValueError("Unsupported toolchain lock")
    for name, repository in REPOSITORIES.items():
        item = lock["components"][name]
        if item["repository"] != repository or not re.fullmatch(r"[0-9a-f]{40}", item["revision"]):
            raise ValueError("Invalid locked repository/revision: " + name)
        if tree_hash(bundle / "sources" / name) != item["tree_sha256"]:
            raise ValueError("Source hash mismatch: " + name)
    if set(p.name for p in bundle.iterdir()) != {"sources", "CMakeLists.txt", "README.md", "lock.json"}:
        raise ValueError("Unexpected bundle entries; regenerate instead of mixing versions")
    if set(p.name for p in (bundle / "sources").iterdir()) != set(REPOSITORIES):
        raise ValueError("Unexpected source components")
    if (bundle / "CMakeLists.txt").read_text() != CMAKE or (bundle / "README.md").read_text() != README:
        raise ValueError("Generated packaging differs")
    dependencies = bundle / "sources/forge/cmake/Dependencies.cmake"
    for component in ("RUNTIME", "STDLIB"):
        if pin(dependencies, "FORGE_" + component + "_REVISION") != lock["components"]["forge-" + component.lower()]["revision"]:
            raise ValueError("Compiler/component pin mismatch")
    if pin(bundle / "sources/forge-stdlib/cmake/dependencies.cmake", "FORGE_RUNTIME_REVISION") != lock["components"]["forge-runtime"]["revision"]:
        raise ValueError("Stdlib/runtime pin mismatch")


def repository(name, args):
    if args.source_root:
        result = args.source_root.resolve() / name
        if not result.is_dir():
            raise ValueError("Missing local repository: " + str(result))
        return result
    result = args.cache_dir.expanduser().resolve() / (name + ".git")
    result.parent.mkdir(parents=True, exist_ok=True)
    if not result.exists():
        subprocess.run(["git", "clone", "--bare", REPOSITORIES[name], str(result)],
                       check=True, env={**os.environ, "GIT_MASTER": "1"})
    else:
        if git(result, "remote", "get-url", "origin").decode().strip() != REPOSITORIES[name]:
            raise ValueError("Cache origin mismatch: " + str(result))
        git(result, "fetch", "--prune", "origin", "+refs/heads/*:refs/heads/*", "+refs/tags/*:refs/tags/*")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", help="Compiler commit, tag or branch; runtime/stdlib follow its pins")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source-root", type=Path, help="Parent of committed local forge, forge-runtime, forge-stdlib repositories")
    parser.add_argument("--cache-dir", type=Path, default=Path.home() / ".cache/portfolio-forge-toolchain")
    parser.add_argument("--toolchain", type=Path, default=ROOT / "backend-forge/toolchain")
    args = parser.parse_args()
    if bool(args.revision) == args.check:
        parser.error("Choose exactly one of --check or --revision")
    bundle = args.toolchain.resolve()
    lock_path = bundle / "lock.json"
    if args.check:
        verify(bundle, json.loads(lock_path.read_text()))
        print("Forge toolchain hashes and dependency pins verified")
        return
    bundle.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".forge-update-", dir=bundle.parent) as temporary:
        stage = Path(temporary) / "toolchain"
        (stage / "sources").mkdir(parents=True)
        components = {}
        compiler = export(repository("forge", args), args.revision, stage / "sources/forge")
        deps = stage / "sources/forge/cmake/Dependencies.cmake"
        revisions = {"forge": compiler,
                     "forge-runtime": pin(deps, "FORGE_RUNTIME_REVISION"),
                     "forge-stdlib": pin(deps, "FORGE_STDLIB_REVISION")}
        for name, revision in revisions.items():
            target = stage / "sources" / name
            if name != "forge":
                export(repository(name, args), revision, target)
            components[name] = dict(repository=REPOSITORIES[name], revision=revision,
                                    tree_sha256=tree_hash(target))
        (stage / "CMakeLists.txt").write_text(CMAKE)
        (stage / "README.md").write_text(README)
        lock = dict(schema=1, components=components)
        (stage / "lock.json").write_text(json.dumps(lock, indent=2) + "\n")
        verify(stage, lock)
        backup = Path(temporary) / "previous"
        existed = bundle.exists()
        if existed:
            bundle.rename(backup)
        try:
            stage.rename(bundle)
        except BaseException:
            if bundle.exists():
                shutil.rmtree(bundle)
            if existed:
                backup.rename(bundle)
            raise
    print(json.dumps(lock, indent=2))


if __name__ == "__main__":
    main()
